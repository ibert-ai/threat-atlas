#!/usr/bin/env python3
"""Fail closed when Radar's published licence notice or linked legal code changes."""
import argparse, hashlib, html, json, re, urllib.request
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
NOTICE = 'https://developers.cloudflare.com/radar/'
LEGAL = 'https://creativecommons.org/licenses/by-nc/4.0/legalcode.en'
def read(url):
    req=urllib.request.Request(url, headers={'User-Agent':'ThreatAtlas-license-review/alpha'})
    with urllib.request.urlopen(req, timeout=30) as response:
        return response.read(2_000_000).decode('utf-8')
def text(value):
    return ' '.join(html.unescape(re.sub('<[^>]+>', ' ', re.sub(r'<(script|style)\b.*?</\1>', '', value, flags=re.S))).split())
def fingerprint():
    notice=text(read(NOTICE))
    match=re.search(r'Data available via Radar API endpoints.*?license\.', notice)
    if not match: raise RuntimeError('Radar licence notice not found; manual review required')
    legal=text(read(LEGAL))
    start=legal.find('Creative Commons Attribution-NonCommercial 4.0 International')
    if start<0: raise RuntimeError('Legal code heading not found')
    return {'notice':match.group(0), 'notice_sha256':hashlib.sha256(match.group(0).encode()).hexdigest(), 'legal_sha256':hashlib.sha256(legal[start:].encode()).hexdigest()}
def main():
    p=argparse.ArgumentParser();p.add_argument('--record-review',action='store_true');p.add_argument('--header',action='store_true');args=p.parse_args()
    current=fingerprint();file=ROOT/'docs/CLOUDFLARE-LICENSE.json'
    if args.record_review:
        from datetime import datetime, timezone
        current.update(reviewed_at=datetime.now(timezone.utc).isoformat(),notice_url=NOTICE,license_url=LEGAL,scope='Noncommercial alpha only; commercial use requires separate authorization')
        file.write_text(json.dumps(current,indent=2)+'\n')
    approved=json.loads(file.read_text())
    for key in ('notice_sha256','legal_sha256'):
        if current[key]!=approved[key]: raise RuntimeError('Cloudflare licence changed: release blocked. Review and update notice, consent revision, tests and approval record; never automatically accept.')
    if args.header:
        version=json.loads((ROOT/'version.json').read_text());release=version['version']+('-'+version['prerelease'] if version.get('prerelease') else '')
        key=f"{release}+{version['build']}:{approved['notice_sha256']}:{approved['legal_sha256']}"
        (ROOT/'macos/RadarLicense.h').write_text('// Generated by licence check; full release/build and terms identity.\n#define TA_RADAR_CONSENT @'+json.dumps(key)+'\n')
    print('Radar licence unchanged against reviewed terms; release check PASS')
if __name__=='__main__': main()
