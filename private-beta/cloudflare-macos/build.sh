#!/bin/sh
set -eu
cd "$(dirname "$0")"
VERSION=0.7.0
BUILD=10
OUT="${ATLAS_BETA_OUTPUT:-/private/tmp/ThreatAtlas-Radar-PrivateBeta}"
mkdir -p "$OUT/AtlasSOC.app/Contents/MacOS" "$OUT/AtlasSOC.app/Contents/Resources"
APP="$OUT/AtlasSOC.app"
# Cloudflare Radar licence gate: fail closed if the published notice or CC BY-NC 4.0 legal code
# changed since the reviewed record (docs/CLOUDFLARE-LICENSE.json) or cannot be fetched. Never
# update the record automatically; see docs/CLOUDFLARE-RADAR-ALPHA.md (PR #17) for the review steps.
python3 -I ../../scripts/check-cloudflare-license.py
TERMS="$OUT/RadarLicense.generated.swift"
python3 -I - "$VERSION" "$BUILD" "$TERMS" <<'PY'
import json, sys
version, build, out = sys.argv[1:4]
t = json.load(open('../../docs/CLOUDFLARE-LICENSE.json'))
s = lambda v: json.dumps(v, ensure_ascii=False)
open(out, 'w').write(
    '// Generated by build.sh after the Cloudflare licence check passed. Do not edit.\n'
    'import Foundation\n'
    f'let radarLicenseTerms = LicenseTerms(version: {s(version)}, build: {s(build)}, notice: {s(t["notice"])}, '
    f'noticeSHA256: {s(t["notice_sha256"])}, legalSHA256: {s(t["legal_sha256"])}, '
    f'noticeURL: URL(string: {s(t["notice_url"])})!, licenseURL: URL(string: {s(t["license_url"])})!, '
    f'scope: {s(t["scope"])})\n')
PY
# The map is drawn by the shared screensaver core (crates/core). Universal by default (Apple silicon
# and Intel); ATLAS_BETA_ARCHS="arm64" builds one slice. SwiftUI APIs used here need macOS 14.
command -v cargo >/dev/null 2>&1 || PATH="$HOME/.cargo/bin:$PATH"
export MACOSX_DEPLOYMENT_TARGET=14.0
set --
for arch in ${ATLAS_BETA_ARCHS:-arm64 x86_64}; do
  case "$arch" in
    arm64) target=aarch64-apple-darwin ;;
    x86_64) target=x86_64-apple-darwin ;;
    *) echo "Unknown architecture: $arch" >&2; exit 1 ;;
  esac
  cargo build --locked --release -p threat-atlas-core --target "$target" --manifest-path ../../Cargo.toml
  CORE="${CARGO_TARGET_DIR:-../../target}/$target/release/libthreat_atlas_core.a"
  xcrun swiftc -target "$arch-apple-macos14" -module-cache-path "$OUT/module-cache-$arch" -parse-as-library \
    -import-objc-header RadarCoreFFI.h RadarCore.swift RadarModel.swift CoreAtlasView.swift LicenseConsent.swift \
    "$TERMS" RadarApp.swift "$CORE" -o "$OUT/AtlasRadar-$arch" \
    -framework SwiftUI -framework Security -framework CoreFoundation -framework SystemConfiguration -liconv
  set -- "$@" "$OUT/AtlasRadar-$arch"
done
lipo -create "$@" -output "$APP/Contents/MacOS/AtlasRadar"
rm -f "$@"
cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?><!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd"><plist version="1.0"><dict><key>CFBundleIdentifier</key><string>dev.threatatlas.private.radar</string><key>CFBundleName</key><string>AtlasSOC</string><key>CFBundleExecutable</key><string>AtlasRadar</string><key>CFBundleShortVersionString</key><string>$VERSION</string><key>CFBundleVersion</key><string>$BUILD</string><key>LSMinimumSystemVersion</key><string>14.0</string><key>NSHighResolutionCapable</key><true/></dict></plist>
PLIST
cp ../../assets/atlassoc/sentinel/AtlasSOC.icns "$APP/Contents/Resources/AtlasSOC.icns"
/usr/libexec/PlistBuddy -c "Add :CFBundleIconFile string AtlasSOC.icns" "$APP/Contents/Info.plist"
codesign --force --sign - "$APP"
# The CL Cloudflare Radar TEST token must never ship. On a machine whose Keychain holds it, fail the
# build if its bytes appear in the app; elsewhere the check reports SKIP (exit 2) and the build goes on.
token_check=0
python3 -I ../../scripts/check-test-token-absent.py "$APP" || token_check=$?
if [ "$token_check" -eq 1 ]; then echo "Build rejected: test token found in $APP" >&2; exit 1; fi
printf '%s\n' "$APP"
